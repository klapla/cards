/* ============================================================
   ВЫБОР ФРАЗЫ
   ============================================================ */
function pickPenguin(context, noRepeat = true) {
  const pool = PENGUIN_PHRASES[context] || PENGUIN_PHRASES.trail;
  if (!pool || !pool.length) return '🐧';
  const lastKey = 'penguin_last_' + context;
  const last = localStorage.getItem(lastKey);
  let idx = Math.floor(Math.random() * pool.length);
  if (noRepeat && pool.length > 1) {
    let tries = 0;
    while (pool[idx] === last && tries < 10) {
      idx = Math.floor(Math.random() * pool.length);
      tries++;
    }
  }
  const phrase = pool[idx];
  localStorage.setItem(lastKey, phrase);
  return phrase;
}

function timeContext() {
  const h = new Date().getHours();
  if (h >= 5 && h < 12) return 'morning';
  if (h >= 12 && h < 18) return 'day';
  return 'evening';
}

function penguinForTrail() {
  const streak = (typeof data !== 'undefined' && data.settings && data.settings.streak) || 0;
  const lastStudy = (typeof data !== 'undefined' && data.settings && data.settings.lastStudyDate) || null;
  const today = new Date().toDateString();
  const yesterday = new Date(Date.now() - 86400000).toDateString();

  if (lastStudy && lastStudy !== today && lastStudy !== yesterday) {
    return pickPenguin('comeback');
  }
  if (streak > 0 && lastStudy === today) {
    return pickPenguin('streak');
  }
  if (streak === 0 && lastStudy && lastStudy !== today) {
    return pickPenguin('noStreak');
  }
  return pickPenguin(timeContext());
}

function penguinForFinish(pct, hadErrors = true) {
  if (pct >= 100 && !hadErrors) return pickPenguin('perfect');
  if (pct >= 90) return pickPenguin('win');
  if (pct >= 70) return pickPenguin('good');
  if (pct >= 50) return pickPenguin('ok');
  return pickPenguin('fail');
}

function penguinForLearning(mode) {
  if (mode === 'dictation') return pickPenguin('dictation');
  if (mode === 'letters') return pickPenguin('letters');
  if (mode === 'sentence') return pickPenguin('sentence');
  return pickPenguin('trail');
}

function penguinForLearningFinish(mode, pct, hadErrors = true) {
  if (pct >= 100 && !hadErrors) {
    if (mode === 'dictation') return pickPenguin('dictationWin');
    if (mode === 'letters') return pickPenguin('lettersWin');
    if (mode === 'sentence') return pickPenguin('sentenceWin');
    return pickPenguin('perfect');
  }
  return penguinForFinish(pct, hadErrors);
}

function finishEmoji(pct, hadErrors = true) {
  if (pct >= 100 && !hadErrors) return '🏆';
  if (pct >= 90) return '🎉';
  if (pct >= 70) return '🐧';
  if (pct >= 50) return '👍';
  return '🧊';
}

function penguinWelcome() {
  if (typeof data !== 'undefined' && data.settings && !data.settings.onboardingDone) {
    return pickPenguin('welcome');
  }
  return penguinForTrail();
}
